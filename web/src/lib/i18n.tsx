export type Lang = keyof typeof dictionary;
export type Key = keyof (typeof dictionary)['tr'];

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string };

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = localStorage.getItem('lang');
    if (saved === 'tr' || saved === 'en') return saved;
    return navigator.language.startsWith('tr') ? 'tr' : 'en';
  });

  const value = useMemo<Ctx>(() => ({
    lang,
    setLang: (l) => {
      localStorage.setItem('lang', l);
      document.documentElement.lang = l;
      setLang(l);
    },
    t: (key, vars) => {
      let text: string = dictionary[lang][key] ?? dictionary.en[key] ?? key;
      if (vars) {
        for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
      }
      return text;
    },
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n needs I18nProvider');
  return ctx;
}
